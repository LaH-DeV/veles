// Command clonegen writes ast/clone_gen.go: a deep copy of every node type
// declared in ast/ast.go, so that ast.Clone copies a tree without
// reflection. Run it with `go generate ./ast` after changing a node type;
// TestGeneratedIsCurrent fails until you do.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	goast "go/ast"
	"go/parser"
	"go/token"
	"os"
	"sort"
	"strings"
)

func main() {
	src, err := os.ReadFile("ast.go")
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	out, err := generate(src)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile("clone_gen.go", out, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// model is what generate reads from ast.go: the struct types, the node
// interfaces, and which pointer types implement each interface.
type model struct {
	structs map[string]*goast.StructType
	ifaces  map[string][]string // interface -> its methods, embedded Node expanded
	methods map[string][]string // type -> the methods declared on *type
	names   []string            // struct names in source order
	inames  []string            // interface names in source order
}

func generate(src []byte) ([]byte, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "ast.go", src, 0)
	if err != nil {
		return nil, err
	}
	m := &model{structs: map[string]*goast.StructType{}, ifaces: map[string][]string{}, methods: map[string][]string{}}
	for _, d := range file.Decls {
		switch d := d.(type) {
		case *goast.GenDecl:
			for _, s := range d.Specs {
				ts, ok := s.(*goast.TypeSpec)
				if !ok {
					continue
				}
				switch t := ts.Type.(type) {
				case *goast.StructType:
					m.structs[ts.Name.Name] = t
					m.names = append(m.names, ts.Name.Name)
				case *goast.InterfaceType:
					var ms []string
					for _, f := range t.Methods.List {
						if len(f.Names) == 0 {
							ms = append(ms, m.ifaces[f.Type.(*goast.Ident).Name]...)
						}
						for _, n := range f.Names {
							ms = append(ms, n.Name)
						}
					}
					m.ifaces[ts.Name.Name] = ms
					m.inames = append(m.inames, ts.Name.Name)
				}
			}
		case *goast.FuncDecl:
			if d.Recv == nil {
				continue
			}
			recv := d.Recv.List[0].Type
			if star, ok := recv.(*goast.StarExpr); ok {
				recv = star.X
			}
			name := recv.(*goast.Ident).Name
			m.methods[name] = append(m.methods[name], d.Name.Name)
		}
	}
	for name := range m.structs {
		if strings.HasPrefix(name, "_") {
			return nil, fmt.Errorf("unexpected type %s", name)
		}
		for _, f := range m.structs[name].Fields.List {
			if len(f.Names) == 0 {
				return nil, fmt.Errorf("%s has an embedded field; clonegen does not copy those", name)
			}
		}
	}

	var b bytes.Buffer
	b.WriteString(`// Code generated by ast/internal/clonegen from ast.go; DO NOT EDIT.

package ast

// cloner copies one tree. The declarations and named types the parser
// reaches twice (an impl written in a struct's body is also in the file's
// declarations; a desugared declaration shares its target type) are copied
// once each, so the copy shares exactly what the original shares.
type cloner struct {
`)
	memo := m.memoized()
	for _, n := range memo {
		fmt.Fprintf(&b, "\tseen%s map[*%s]*%s\n", n, n, n)
	}
	b.WriteString("}\n")

	for _, n := range m.names {
		m.emitStruct(&b, n, contains(memo, n))
	}
	for _, n := range m.inames {
		m.emitIface(&b, n)
	}
	return format.Source(b.Bytes())
}

// memoized is every type the parser may reach twice: the declarations, and
// NamedType. TestCloneKeepsSharing checks that no other node is shared.
func (m *model) memoized() []string {
	var out []string
	for _, n := range m.names {
		if n == "NamedType" || m.implements(n, "Decl") {
			out = append(out, n)
		}
	}
	return out
}

func (m *model) implements(typ, iface string) bool {
	for _, want := range m.ifaces[iface] {
		if !contains(m.methods[typ], want) {
			return false
		}
	}
	return true
}

// deep reports whether a value of the struct type has anything to replace.
func (m *model) deep(name string) bool {
	for _, f := range m.structs[name].Fields.List {
		if m.fieldDeep(f.Type) {
			return true
		}
	}
	return false
}

func (m *model) fieldDeep(t goast.Expr) bool {
	switch t := t.(type) {
	case *goast.StarExpr:
		id, ok := t.X.(*goast.Ident)
		return ok && m.structs[id.Name] != nil
	case *goast.ArrayType:
		return true
	case *goast.Ident:
		if m.ifaces[t.Name] != nil {
			return true
		}
		if m.structs[t.Name] != nil {
			return m.deep(t.Name)
		}
	}
	return false // a basic type, `any`, or a type of another package: shared
}

// emitStruct writes clone<T> (a copy of a node) and fix<T> (replace, in a
// struct copied by value, what still points into the original).
func (m *model) emitStruct(b *bytes.Buffer, name string, memo bool) {
	deep := m.deep(name)
	fmt.Fprintf(b, "\nfunc (c *cloner) clone%s(x *%s) *%s {\n\tif x == nil {\n\t\treturn nil\n\t}\n", name, name, name)
	if memo {
		fmt.Fprintf(b, "\tif n, ok := c.seen%s[x]; ok {\n\t\treturn n\n\t}\n", name)
		fmt.Fprintf(b, "\tif c.seen%s == nil {\n\t\tc.seen%s = map[*%s]*%s{}\n\t}\n", name, name, name, name)
	}
	b.WriteString("\tn := new(" + name + ")\n")
	if memo {
		fmt.Fprintf(b, "\tc.seen%s[x] = n\n", name)
	}
	b.WriteString("\t*n = *x\n")
	if deep {
		fmt.Fprintf(b, "\tc.fix%s(n)\n", name)
	}
	b.WriteString("\treturn n\n}\n")
	if !deep {
		return
	}
	fmt.Fprintf(b, "\nfunc (c *cloner) fix%s(n *%s) {\n", name, name)
	for _, f := range m.structs[name].Fields.List {
		for _, fn := range f.Names {
			m.emitFix(b, "n."+fn.Name, f.Type, 1)
		}
	}
	b.WriteString("}\n")
}

// emitFix writes the statement that makes the lvalue v, of type t, the
// copy's own.
func (m *model) emitFix(b *bytes.Buffer, v string, t goast.Expr, depth int) {
	if !m.fieldDeep(t) {
		return
	}
	ind := strings.Repeat("\t", depth)
	switch t := t.(type) {
	case *goast.StarExpr:
		name := t.X.(*goast.Ident).Name
		fmt.Fprintf(b, "%s%s = c.clone%s(%s)\n", ind, v, name, v)
	case *goast.Ident:
		if m.ifaces[t.Name] != nil {
			fmt.Fprintf(b, "%s%s = c.clone%s(%s)\n", ind, v, t.Name, v)
		} else {
			fmt.Fprintf(b, "%sc.fix%s(&%s)\n", ind, t.Name, v)
		}
	case *goast.ArrayType:
		if t.Len != nil {
			panic("clonegen: fixed-size arrays are not supported")
		}
		elem := typeString(t.Elt)
		s := fmt.Sprintf("s%d", depth)
		fmt.Fprintf(b, "%sif %s != nil {\n", ind, v)
		fmt.Fprintf(b, "%s\t%s := make([]%s, len(%s))\n", ind, s, elem, v)
		fmt.Fprintf(b, "%s\tcopy(%s, %s)\n", ind, s, v)
		if m.fieldDeep(t.Elt) {
			i := fmt.Sprintf("i%d", depth)
			fmt.Fprintf(b, "%s\tfor %s := range %s {\n", ind, i, s)
			m.emitFix(b, s+"["+i+"]", t.Elt, depth+2)
			fmt.Fprintf(b, "%s\t}\n", ind)
		}
		fmt.Fprintf(b, "%s\t%s = %s\n", ind, v, s)
		fmt.Fprintf(b, "%s}\n", ind)
	}
}

// emitIface writes clone<I>: a copy of whichever node the interface holds.
func (m *model) emitIface(b *bytes.Buffer, iface string) {
	var impls []string
	for _, n := range m.names {
		if m.implements(n, iface) {
			impls = append(impls, n)
		}
	}
	sort.Strings(impls)
	fmt.Fprintf(b, "\nfunc (c *cloner) clone%s(v %s) %s {\n\tswitch v := v.(type) {\n", iface, iface, iface)
	for _, n := range impls {
		fmt.Fprintf(b, "\tcase *%s:\n\t\treturn c.clone%s(v)\n", n, n)
	}
	b.WriteString("\t}\n\treturn v // nil, or a value type: nothing to copy\n}\n")
}

func typeString(t goast.Expr) string {
	switch t := t.(type) {
	case *goast.Ident:
		return t.Name
	case *goast.StarExpr:
		return "*" + typeString(t.X)
	case *goast.ArrayType:
		return "[]" + typeString(t.Elt)
	case *goast.SelectorExpr:
		return typeString(t.X) + "." + t.Sel.Name
	case *goast.InterfaceType:
		return "any"
	}
	panic(fmt.Sprintf("clonegen: unsupported type %T", t))
}

func contains(xs []string, x string) bool {
	for _, y := range xs {
		if y == x {
			return true
		}
	}
	return false
}
