var updateUnicode = flag.Bool("update-unicode", false, "rewrite regex/unicode.vs from Go's unicode tables")

// TestRegexUnicodeTables checks regex/unicode.vs, the Unicode data behind
// `\p{…}`, the `u` flag and Unicode case folding in std/regex (D182), against
// the tables of the Go toolchain. It is generated, not written: after a Go
// release moves the Unicode version, or a change here:
//
//	go test ./std -run RegexUnicodeTables -update-unicode
func TestRegexUnicodeTables(t *testing.T) {
	want := generateUnicode()
	path := "regex/unicode.vs"
	if *updateUnicode {
		if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := FS.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if strings.ReplaceAll(string(got), "\r\n", "\n") != want {
		t.Fatalf("%s is out of date (Unicode %s in this Go): go test ./std -run RegexUnicodeTables -update-unicode", path, unicode.Version)
	}
}

// pairs flattens a range table into sorted, merged `lo, hi` pairs.
func pairs(tables ...*unicode.RangeTable) []int {
	var spans [][2]int
	for _, t := range tables {
		for _, r := range t.R16 {
			spans = appendStride(spans, int(r.Lo), int(r.Hi), int(r.Stride))
		}
		for _, r := range t.R32 {
			spans = appendStride(spans, int(r.Lo), int(r.Hi), int(r.Stride))
		}
	}
	sort.Slice(spans, func(i, j int) bool { return spans[i][0] < spans[j][0] })
	var out []int
	for _, s := range spans {
		if n := len(out); n > 0 && s[0] <= out[n-1]+1 {
			if s[1] > out[n-1] {
				out[n-1] = s[1]
			}
			continue
		}
		out = append(out, s[0], s[1])
	}
	return out
}

func appendStride(spans [][2]int, lo, hi, stride int) [][2]int {
	if stride == 1 {
		return append(spans, [2]int{lo, hi})
	}
	for c := lo; c <= hi; c += stride {
		spans = append(spans, [2]int{c, c})
	}
	return spans
}

func list(name string, values []int, doc string) string {
	var b strings.Builder
	if doc != "" {
		fmt.Fprintf(&b, "/// %s\n", doc)
	}
	fmt.Fprintf(&b, "const %s: List<i64> = [", name)
	for i, v := range values {
		if i%16 == 0 {
			b.WriteString("\n ")
		}
		fmt.Fprintf(&b, " %d,", v)
	}
	b.WriteString("\n]\n\n")
	return b.String()
}

func sortedKeys[V any](m map[string]V) []string {
	var keys []string
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func generateUnicode() string {
	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by `go test ./std -run RegexUnicodeTables -update-unicode` from the\n")
	fmt.Fprintf(&b, "// Unicode tables of the Go toolchain (Unicode %s). Do not edit.\n", unicode.Version)
	b.WriteString("//\n// The data behind `\\p{…}`, the `u` flag and Unicode case folding in std/regex\n// (D182): general categories, scripts, the properties a pattern's `\\d \\w \\s`\n// need, and the case-folding orbits. Every range list is sorted, merged\n// `lo, hi, lo, hi, …` pairs, both ends in.\n\n")

	cats := sortedKeys(unicode.Categories)
	scripts := sortedKeys(unicode.Scripts)
	for _, name := range cats {
		b.WriteString(list("cat"+name, pairs(unicode.Categories[name]), ""))
	}
	for _, name := range scripts {
		b.WriteString(list("script"+strings.ReplaceAll(name, "_", ""), pairs(unicode.Scripts[name]), ""))
	}
	b.WriteString(list("unicodeSpace", pairs(unicode.White_Space), "White_Space: what `\\s` matches under the `u` flag."))
	b.WriteString(list("unicodeWord", pairs(unicode.L, unicode.M, unicode.Nd, unicode.Pc), "Letters, marks, decimal digits and connector punctuation: what `\\w` and `\\b` mean under the `u` flag."))

	// case folding: each code point with other cases maps to the next one in
	// its orbit (unicode.SimpleFold), so following the map visits them all
	var fold []int
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if next := unicode.SimpleFold(r); next != r {
			fold = append(fold, int(r), int(next))
		}
	}
	b.WriteString(list("foldNext", fold, "Case folding (unicode.SimpleFold): `c, next` pairs sorted by `c`; the next code point in the orbit of `c`, back to the first at the end."))

	b.WriteString("/// The ranges of the general category or script `name`, or null when there is\n/// none: `L`, `Lu`, `Nd`, `Greek`, `Han`, …\nconst fun unicodeProperty(name: string): List<i64>? => when (name) {\n")
	// the arrows are aligned, as `veles fmt` writes them
	width := len("else")
	for _, name := range append(append([]string{}, cats...), scripts...) {
		if n := len(fmt.Sprintf("%q", name)); n > width {
			width = n
		}
	}
	for _, name := range cats {
		fmt.Fprintf(&b, "  %s => cat%s\n", pad(fmt.Sprintf("%q", name), width), name)
	}
	for _, name := range scripts {
		fmt.Fprintf(&b, "  %s => script%s\n", pad(fmt.Sprintf("%q", name), width), strings.ReplaceAll(name, "_", ""))
	}
	fmt.Fprintf(&b, "  %s => null\n}\n", pad("else", width))
	return b.String()
}

// pad right-pads s with spaces to width bytes.
func pad(s string, width int) string {
	return s + strings.Repeat(" ", width-len(s))
}
